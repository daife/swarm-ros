#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
CONFIG_FILE="${1:-}"
source "${SCRIPT_DIR}/_load_config.sh" "${CONFIG_FILE}"

echo "[30_training_launch] backend=${ENV_BACKEND}, gui=${GAZEBO_GUI}, world=${WORLD_NAME}"

LAUNCH_ARGS=(
  "env_backend:=${ENV_BACKEND}"
  "gazebo_gui:=${GAZEBO_GUI}"
  "world_name:=${WORLD_NAME}"
  "world_sdf:=${WORLD_SDF}"
  "num_pursuers:=${NUM_PURSUERS}"
  "num_evaders:=${NUM_EVADERS}"
  "max_episodes:=${MAX_EPISODES}"
  "max_steps:=${MAX_STEPS}"
  "reset_policy:=${RESET_POLICY}"
  "world_mode:=${WORLD_MODE}"
  "seed_mode:=${SEED_MODE}"
  "seed_value:=${SEED_VALUE}"
  "obstacle_density:=${OBSTACLE_DENSITY}"
  "collision_distance:=${COLLISION_DISTANCE}"
  "capture_radius:=${CAPTURE_RADIUS}"
  "capture_steps:=${CAPTURE_STEPS}"
  "collision_penalty:=${COLLISION_PENALTY}"
  "pursuer_algo:=${PURSUER_ALGO}"
  "pursuer_train_mode:=${PURSUER_TRAIN_MODE}"
  "evader_algo:=${EVADER_ALGO}"
  "evader_train_mode:=${EVADER_TRAIN_MODE}"
  "max_accel:=${MAX_ACCEL}"
  "pursuer_max_accel:=${PURSUER_MAX_ACCEL}"
  "evader_max_accel:=${EVADER_MAX_ACCEL}"
  "checkpoint_dir:=${CHECKPOINT_DIR}"
  "checkpoint_prefix:=${CHECKPOINT_PREFIX}"
  "buffer_capacity:=${BUFFER_CAPACITY}"
  "batch_size:=${BATCH_SIZE}"
  "warmup_steps:=${WARMUP_STEPS}"
  "train_updates_per_step:=${TRAIN_UPDATES_PER_STEP}"
  "discount_gamma:=${DISCOUNT_GAMMA}"
  "target_tau:=${TARGET_TAU}"
  "pursuer_actor_lr:=${PURSUER_ACTOR_LR}"
  "pursuer_critic_lr:=${PURSUER_CRITIC_LR}"
  "evader_actor_lr:=${EVADER_ACTOR_LR}"
  "evader_critic_lr:=${EVADER_CRITIC_LR}"
  "exploration_noise_std:=${EXPLORATION_NOISE_STD}"
  "policy_update_interval:=${POLICY_UPDATE_INTERVAL}"
  "use_synthetic_obs_when_missing:=${USE_SYNTHETIC_OBS_WHEN_MISSING}"
  "world_half_extent:=${WORLD_HALF_EXTENT}"
  "spawn_half_extent:=${SPAWN_HALF_EXTENT}"
  "spawn_attempts:=${SPAWN_ATTEMPTS}"
  "obstacle_model_package:=${OBSTACLE_MODEL_PACKAGE}"
  "obstacle_pool_box:=${OBSTACLE_POOL_BOX}"
  "obstacle_pool_rect:=${OBSTACLE_POOL_RECT}"
  "obstacle_pool_cylinder:=${OBSTACLE_POOL_CYLINDER}"
  "obstacle_spawn_attempts:=${OBSTACLE_SPAWN_ATTEMPTS}"
  "obstacle_min_clearance:=${OBSTACLE_MIN_CLEARANCE}"
  "obstacle_staging_x:=${OBSTACLE_STAGING_X}"
  "obstacle_staging_y:=${OBSTACLE_STAGING_Y}"
  "obstacle_staging_stride:=${OBSTACLE_STAGING_STRIDE}"
  "pursuer_name_prefix:=${PURSUER_PREFIX}"
  "evader_name_prefix:=${EVADER_PREFIX}"
  "agent_model_package:=${AGENT_MODEL_PACKAGE}"
  "agent_staging_x:=${AGENT_STAGING_X}"
  "agent_staging_y:=${AGENT_STAGING_Y}"
  "agent_staging_stride:=${AGENT_STAGING_STRIDE}"
  "gazebo_controller_enabled:=${GAZEBO_CONTROLLER_ENABLED}"
  "gazebo_controller_dt:=${GAZEBO_CONTROLLER_DT}"
  "gazebo_max_speed:=${GAZEBO_MAX_SPEED}"
  "gazebo_pursuer_max_speed:=${GAZEBO_PURSUER_MAX_SPEED}"
  "gazebo_evader_max_speed:=${GAZEBO_EVADER_MAX_SPEED}"
  "gazebo_linear_drag:=${GAZEBO_LINEAR_DRAG}"
  "gazebo_control_requires_reset:=${GAZEBO_CONTROL_REQUIRES_RESET}"
  "fixed_z:=${FIXED_Z}"
  "initial_reset_delay_sec:=${INITIAL_RESET_DELAY_SEC}"
  "reset_agents_delay_sec:=${RESET_AGENTS_DELAY_SEC}"
  "reset_grace_steps:=${RESET_GRACE_STEPS}"
  "always_reset_world:=${ALWAYS_RESET_WORLD}"
  "mock_dt:=${MOCK_DT}"
  "mock_max_speed:=${MOCK_MAX_SPEED}"
  "mock_linear_drag:=${MOCK_LINEAR_DRAG}"
  "mock_spawn_half_extent:=${MOCK_SPAWN_HALF_EXTENT}"
)

if [[ -n "${PURSUER_WEIGHTS}" ]]; then
  LAUNCH_ARGS+=( "pursuer_weights:=${PURSUER_WEIGHTS}" )
fi

if [[ -n "${EVADER_WEIGHTS}" ]]; then
  LAUNCH_ARGS+=( "evader_weights:=${EVADER_WEIGHTS}" )
fi

exec ros2 launch swarm_bringup training_launch.py "${LAUNCH_ARGS[@]}"
